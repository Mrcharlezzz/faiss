"""Export the numbers behind the results slides (12–14) to results.js, from runs 3 and 4.

Run from analysis/:
    python scripts/export_results.py [out.js]

Every number goes through scripts/run3_data.py, the same functions as run3_extended.ipynb and
run4_glove25.ipynb (Figures 2, 3, entry-gain survival, Figure 8). Nothing is digitized from the PNGs.
"""
import json
import sys
from datetime import date
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run3_data as rd  # noqa: E402

OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "results.js")
XS = np.logspace(-1, 2, 61)  # entry-gain thresholds, % closer (0.1% .. 100%), log spaced
THRESH = (5, 10, 30, 50)


def r(v, n=4):
    return None if v is None or not np.isfinite(v) else round(float(v), n)


def stats(t, col):
    """mean and 95% t interval from an across_seeds() row."""
    return dict(mean=r(t[(col, "mean")]), lo=r(t[(col, "ci_lo")]), hi=r(t[(col, "ci_hi")]), n=int(t[(col, "n_seeds")]))


out = dict(meta=dict(date=str(date.today()), runs="data/run_3 (Deep1M, GIST1M, Clustered d=16/32), "
                     "run_4 (GloVe-25)", code="scripts/run3_data.py",
                     match="matched recall interpolated in log(1 - recall) on each seed's standard curve",
                     ci="95% t interval across graph seeds"),
           tradeoff={}, matched={}, entry={}, balance={})

for data_dir in ("data/run_3", "data/run_4"):
    data = rd.load(data_dir)
    runs, queries = data.runs, data.queries
    m = rd.matched(runs)

    # Figure 2: curves per (dataset, width, ef0), seed mean and 95% t interval
    for ds in rd._names(runs):
        d = runs[runs.dataset == ds]
        efmax = rd.MATCH_EF_MAX if ds in rd.CLUSTERED else d.ef0.max()
        d = d[d.ef0 <= efmax]
        t = rd.across_seeds(d, ["recall_at_10", "latency_ms", "dist_total"], ["width", "ef0"])
        out["tradeoff"][ds] = {
            str(w): [dict(ef0=int(ef), recall=r(row[("recall_at_10", "mean")], 5),
                          latency=stats(row, "latency_ms"), dist=stats(row, "dist_total"))
                     for (ww, ef), row in t.iterrows() if ww == w]
            for w in rd.WIDTHS}

    # Figure 3 headline: Δ% at matched recall, seed mean over ef0 then across seeds
    for col, key in (("latency_delta_pct", "latency"), ("dist_total_delta_pct", "dist")):
        s = rd.matched_summary(m, col)
        for (ds, w), row in s.iterrows():
            out["matched"].setdefault(ds, {}).setdefault(str(w), {})[key] = dict(
                mean=r(row["mean"], 2), lo=r(row["ci_lo"], 2), hi=r(row["ci_hi"], 2), n=int(row["n_seeds"]))
        # per-ef0 view (recall dependence): Δ% mean and 95% t interval, and the w point's recall (seed mean)
        b = rd.matched_by_ef(m, col, ("mean", "ci_lo", "ci_hi"))
        rec = m.groupby(["dataset", "ef0", "width"], observed=True).recall_at_10.mean()
        for (ds, ef, w), row in b.iterrows():
            cell = out["matched"][ds][str(w)].setdefault("by_ef0", {}).setdefault(str(int(ef)), {})
            cell["recall"] = r(rec[(ds, ef, w)], 5)
            cell[key] = dict(mean=r(row["mean"], 2), lo=r(row["ci_lo"], 2), hi=r(row["ci_hi"], 2))

    # entry-gain survival: share of ALL queries whose ep1 is at least x% closer (seeds pooled, smallest ef0)
    base = queries.groupby("dataset", observed=True).ef0.transform("min")
    q = queries[queries.ef0 == base]
    for (ds, w), g in q.groupby(["dataset", "width"], observed=True):
        gain = np.sort(100 * (1 - np.exp(-g.entry_closer_logratio.dropna().to_numpy())))
        n = len(g)
        out["entry"].setdefault(ds, {})[str(w)] = dict(
            queries=n, changed=r((~g.entry_unchanged).mean()),
            at_least={str(p): r(1 - np.searchsorted(gain, p, side="left") / n) for p in THRESH},
            curve=[[r(x, 3), r(1 - np.searchsorted(gain, x, side="left") / n)] for x in XS])

    # Figure 8: balance per entry-gain group at matched recall (datasets with per-query recall)
    qg = rd.entry_gain_groups(queries)
    names = qg.attrs["group_names"]
    gc = rd.group_curves(qg)
    gm = rd.group_matched(gc)
    bal = rd.across_seeds(gm, ["layer0_saved", "layer1_extra", "net_saved"], ["dataset", "width", "gain_group", "recall_target"])
    size = gc.groupby(["dataset", "width", "gain_group"], observed=True).n_queries.mean()
    for (ds, w, gg, rt), row in bal.iterrows():
        grp = out["balance"].setdefault(ds, {}).setdefault(str(w), {}).setdefault(str(gg), dict(
            name=names[(ds, w)][gg], queries_per_seed=r(size[(ds, w, gg)], 1), targets={}))
        grp["layer1_extra"] = stats(row, "layer1_extra")
        grp["targets"][str(rt)] = dict(layer0_saved=stats(row, "layer0_saved"), net_saved=stats(row, "net_saved"))
    del data, queries, qg, gc

OUT.write_text("// Generated by export_results.py — do not edit by hand.\nwindow.RESULTS = "
               + json.dumps(out, separators=(",", ":")) + ";\n")
print("wrote", OUT, OUT.stat().st_size, "bytes")
